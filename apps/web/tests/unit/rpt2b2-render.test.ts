import { expect, it } from "vitest";
import { mockApi, setDemoLatency } from "../../src/demo/mockApi";
import { renderReport } from "../../src/report/render";

it.each(["en", "id"] as const)("renders verified partial-period data and the recorded completion date in %s", async locale => {
  setDemoLatency(0);
  const view = await mockApi.project("demo-project");
  const source = structuredClone(await mockApi.reportSnapshot("demo-project", view.bundle.simulation_runs[0].simulation_run_id));
  const run = source.design_view.bundle.simulation_runs[0];
  run.completed_at = "2025-12-31T18:00:00Z";
  source.site.timezone = "Asia/Jakarta";
  const summary = run.summary_result!;
  summary.annual_energy_wh = null;
  summary.total_energy_wh = 12000;
  summary.period_duration_hours = 3;
  summary.period_start_time = "2025-01-01T00:00:00+07:00";
  summary.period_end_time = "2025-01-01T03:00:00+07:00";
  summary.monthly_energy = [{ month: "2025-01", energy_wh: 12000 }];
  summary.loss_summary = [];
  summary.specific_yield_wh_per_wp = 12000 / (source.monthly.dc_kwp! * 1000);
  source.summary = structuredClone(summary);
  source.hourly_ac.values = null;
  const html = renderReport(source, { locale, planFigurePng: null });
  expect(html).toContain(locale === "en" ? "Results computed" : "Hasil dihitung");
  expect(html).toContain("2026-01-01");
  expect(html).toContain(locale === "en" ? "simulated period" : "periode simulasi");
  expect(html).toContain(locale === "en" ? "not applicable to a partial period" : "tidak berlaku untuk periode parsial");
  expect(html).toContain("12");
  expect(html).toContain(source.snapshot_sha256);
  expect(html).toContain(locale === "en" ? "Plan figure not supplied" : "Gambar denah tidak disertakan");
  source.monthly.period.pr = null;
  source.summary.performance_ratio = 0;
  const noPoa = renderReport(source, { locale, planFigurePng: null });
  expect(noPoa).toContain('data-report-pr-reason="no_poa_reference"');
  expect(noPoa).toContain(locale === "en" ? "No POA reference" : "Tidak ada referensi POA");
  summary.monthly_energy[0].energy_wh = 13000;
  expect(() => renderReport({ ...source, summary }, { locale, planFigurePng: null })).toThrow();
});

it("renders a recorded nonannual rolling period across thirteen months without inferring annual production", async () => {
  setDemoLatency(0);
  const view = await mockApi.project("demo-project");
  const source = structuredClone(await mockApi.reportSnapshot("demo-project", view.bundle.simulation_runs[0].simulation_run_id));
  const summary = source.summary;
  summary.annual_energy_wh = null;
  summary.total_energy_wh = 13000;
  summary.period_duration_hours = 8760;
  summary.period_start_time = "2025-01-15T00:00:00+07:00";
  summary.period_end_time = "2026-01-15T00:00:00+07:00";
  summary.monthly_energy = Array.from({ length: 13 }, (_, i) => ({ month: i === 12 ? "2026-01" : `2025-${String(i + 1).padStart(2, "0")}`, energy_wh: 1000 }));
  summary.loss_summary = [];
  summary.specific_yield_wh_per_wp = 13000 / (source.monthly.dc_kwp! * 1000);
  source.hourly_ac.values = null;
  const html = renderReport(source, { locale: "en", planFigurePng: null });
  expect(html).toContain("simulated period");
  expect(html).toContain("not applicable to a partial period");
  expect(html).toContain("2025-01"); expect(html).toContain("2026-01");
  expect(html).toContain("data-period-monthly");
});
