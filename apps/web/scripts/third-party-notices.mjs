#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md for everything shipped in the browser bundle:
// production npm dependencies (from package-lock.json) plus bundled assets.
// Development-only tools are not shipped and are not listed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
const check = process.argv.includes("--check");

const rows = [];
for (const [key, meta] of Object.entries(lock.packages)) {
  if (!key || meta.dev || meta.devOptional) continue;
  const dir = path.join(root, key);
  const pkgFile = path.join(dir, "package.json");
  if (!fs.existsSync(pkgFile)) continue;
  const pkg = JSON.parse(fs.readFileSync(pkgFile, "utf8"));
  const licence = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "UNKNOWN";
  rows.push({ name: pkg.name, version: pkg.version, licence, repo: (pkg.repository?.url ?? pkg.repository ?? pkg.homepage ?? "").toString() });
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const assets = [
  ["osifont (osifont-lgpl3fe.woff)", "LGPL-3.0 with GPL font exception", "public/fonts/osifont/LICENSE.md"],
  ["Archivo, Archivo Narrow, IBM Plex Mono, Michroma (via @fontsource)", "OFL-1.1", "node_modules/@fontsource/*/LICENSE"]
];

const md = [
  "# Third-party notices (apps/web)",
  "",
  "Generated by `npm run notices` from package-lock.json. RawiBumi itself is licensed under AGPL-3.0 (see the repository LICENSE).",
  "",
  "## Bundled assets",
  "",
  "| Asset | Licence | Licence text |",
  "|---|---|---|",
  ...assets.map(([a, l, f]) => `| ${a} | ${l} | \`${f}\` |`),
  "",
  "## npm packages shipped in the browser bundle",
  "",
  "| Package | Version | Licence |",
  "|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.licence} |`),
  ""
].join("\n");

const out = path.join(root, "THIRD_PARTY_NOTICES.md");
const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
if (check) {
  if (current !== md) {
    console.error("THIRD_PARTY_NOTICES.md is out of date (run npm run notices).");
    process.exit(1);
  }
  console.log(`Notices up to date (${rows.length} packages).`);
} else {
  fs.writeFileSync(out, md);
  const unknown = rows.filter((r) => r.licence === "UNKNOWN");
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages${unknown.length ? `, ${unknown.length} with unknown licence` : ""}).`);
}
